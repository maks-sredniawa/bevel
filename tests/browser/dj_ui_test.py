import json, os, sys
from pathlib import Path
from playwright.sync_api import sync_playwright
S = Path(__file__).parent
R = []
def check(n, ok, d=''):
    R.append(bool(ok)); print('ok  ' if ok else 'FAIL', n, '' if ok else json.dumps(d, default=str, ensure_ascii=False)[:320], flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(channel='chrome', headless=True, args=['--mute-audio'])
    page = b.new_page(viewport={'width': 1280, 'height': 1000}); errs = []
    page.on('pageerror', lambda e: errs.append(str(e)))
    page.goto('http://127.0.0.1:8766/index.html'); page.wait_for_timeout(700)
    page.set_input_files('#folder-input', os.path.expanduser('~/Music'))
    page.wait_for_function("document.querySelectorAll('.pl-tab').length === 6 && !document.getElementById('status').textContent.includes('saving')", polling=200, timeout=120000)
    page.wait_for_timeout(800)
    w = page.wait_for_timeout; ev = page.evaluate
    check('panel hidden by default', not page.locator('#dj-panel').is_visible())
    check('deck buttons hidden by default', not page.locator('#tracks .row .ld').first.is_visible())
    box = page.locator('#dj-switch').bounding_box(); top = page.locator('#menubar').bounding_box()
    check('switch is in the top bar', top['y'] <= box['y'] <= top['y'] + top['height'], [box, top])
    page.click('#dj-switch'); w(400)
    check('switch shows the panel', page.locator('#dj-panel').is_visible())
    check('switch is lit', page.get_attribute('#dj-switch', 'aria-pressed') == 'true')
    check('panel is above the players', page.locator('#dj-panel').bounding_box()['y'] < page.locator('.work').bounding_box()['y'])
    check('main deck renamed', page.inner_text('#main-deck-legend').upper() == 'MASTER')
    check('empty decks are disabled', page.locator('#deck-a-play').is_disabled() and page.get_attribute('#deck-a', 'data-state') == 'empty')
    page.screenshot(path=str(S / 'dj-empty.png'))
    rows = page.locator('#tracks .row')
    rows.nth(0).locator('.ld[data-deck=a]').click()
    w(150); check('analysing state shows', page.get_attribute('#deck-a', 'data-state') in ('analysing', 'ready'))
    page.wait_for_function("document.getElementById('deck-a').dataset.state === 'ready'", polling=100, timeout=20000)
    rows.nth(1).locator('.ld[data-deck=b]').click()
    page.wait_for_function("document.getElementById('deck-b').dataset.state === 'ready'", polling=100, timeout=20000)
    w(200)
    check('deck shows song and tempo', page.inner_text('#deck-a-title') != 'No track' and float(page.inner_text('#deck-a-bpm')) > 60, [page.inner_text('#deck-a-title'), page.inner_text('#deck-a-bpm')])
    check('row button shows the loaded deck', rows.nth(0).locator('.ld[data-deck=a]').get_attribute('aria-pressed') == 'true')
    page.click('#deck-a-play'); w(900)
    s = ev("retroDJ.state()")
    check('play button plays', s['a']['playing'] and s['a']['position'] > 0.3, s['a'])
    check('play button lights', page.get_attribute('#deck-a-play', 'aria-pressed') == 'true')
    check('time readout moves', page.inner_text('#deck-a-time').startswith('00:0'), page.inner_text('#deck-a-time'))
    lit = ev("(() => { const c = document.getElementById('deck-a-wave'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < d.length; i += 4) if (d[i]) n++; return n; })()")
    check('waveform draws', lit > 500, lit)
    page.locator('#deck-a-high').focus(); page.keyboard.press('Home'); w(100)
    check('EQ fader reaches the deck', ev("retroDJ.state().a.eq.high") == -24)
    page.click('#deck-a-low-kill'); w(80)
    check('kill button works', ev("retroDJ.state().a.eq.kills.low") and page.get_attribute('#deck-a-low-kill', 'aria-pressed') == 'true')
    page.click('#deck-a-low-kill')
    page.locator('#deck-a-filter').fill('-50'); w(80)
    check('filter works', ev("retroDJ.state().a.filter") == -0.5, ev("retroDJ.state().a.filter"))
    page.locator('#deck-a-filter').fill('0')
    page.locator('#crossfader').fill('50'); w(80)
    check('crossfader works', ev("retroDJ.state().crossfader") == 0.5)
    page.locator('#crossfader').fill('-100')
    page.locator('#level-a').fill('80'); w(80)
    check('level works', ev("retroDJ.state().levels.a") == 0.8 and page.inner_text('#level-a-value') == '80%')
    page.locator('#level-a').fill('100')
    page.click('#deck-a-loop-2'); w(100)
    check('loop button', ev("retroDJ.state().a.loop") is not None and page.get_attribute('#deck-a-loop-2', 'aria-pressed') == 'true')
    page.click('#deck-a-loop-2'); w(100)
    check('loop button off', ev("retroDJ.state().a.loop") is None)
    page.select_option('#eq-preset', 'Rock'); w(100)
    check('main equaliser leaves DJ controls alone', ev("document.getElementById('deck-a-mid').value") == '0' and page.inner_text('#deck-a-mid-value') == '0.0 dB', page.inner_text('#deck-a-mid-value'))
    page.select_option('#eq-preset', 'Flat')
    page.click('#deck-a-cue-1'); w(80)
    check('hot cue sets', page.get_attribute('#deck-a-cue-1', 'data-set') == 'true')
    page.click('#deck-a-cue-1', modifiers=['Shift']); w(80)
    check('shift clears a hot cue', page.get_attribute('#deck-a-cue-1', 'data-set') == 'false')
    page.click('#deck-b-sync'); w(100)
    check('sync button', ev("retroDJ.state().b.sync"))
    page.locator('#deck-a-pitch').fill('2'); w(100)
    check('pitch fader', abs(ev("retroDJ.state().a.rate") - 1.02) < 1e-6 and page.inner_text('#deck-a-pitch-value') == '+2.0%')
    page.locator('#deck-a-pitch').fill('0')
    page.click('#deck-a-roll'); w(300); check('roll runs', ev("retroDJ.state().a.loop") is not None)
    w(4600); check('roll ends', ev("retroDJ.state().a.loop") is None and ev("retroDJ.state().a.playing"), ev("retroDJ.state().a"))
    page.click('#deck-a-cue'); w(200)
    check('cue returns and stops', not ev("retroDJ.state().a.playing") and ev("retroDJ.state().a.position") < 1, ev("retroDJ.state().a.position"))
    page.click('#deck-a-play'); w(300); page.click('#deck-a-tape'); w(2300)
    check('tape stop button', not ev("retroDJ.state().a.playing"))
    page.click('#deck-a-play'); w(300); page.click('#deck-a-echo'); w(1300)
    check('echo button', not ev("retroDJ.state().a.playing"))
    page.locator('.tracks-scroll').evaluate('e => e.scrollTop = 0')
    page.select_option('#auto-style', 'mixed'); page.fill('#auto-bars', '8'); page.click('#auto-dj'); 
    page.wait_for_function("retroDJ.state().auto.running && (retroDJ.state().a.playing || retroDJ.state().b.playing)", polling=200, timeout=30000)
    check('Auto DJ starts from the button', page.get_attribute('#auto-dj', 'aria-pressed') == 'true')
    w(800); page.screenshot(path=str(S / 'dj-live.png'))
    status = page.inner_text('#auto-status')
    check('Auto DJ shows what it is doing', status and not status.startswith('Off'), status)
    page.click('#auto-dj'); w(300)
    check('Auto DJ stops from the button', not ev("retroDJ.state().auto.running"))
    ev("retroDJ.pause('a'); retroDJ.pause('b')")
    page.click('#play'); w(500)
    check('normal player still works and takes over', not ev("document.getElementById('audio').paused") and not ev("retroDJ.state().a.playing"))
    page.click('#stop')
    page.reload(); page.wait_for_function("document.querySelectorAll('#tracks .row').length > 0", polling=100); w(500)
    check('DJ mode is remembered', page.locator('#dj-panel').is_visible())
    page.set_viewport_size({'width': 360, 'height': 800}); w(300)
    wide = ev("document.documentElement.scrollWidth")
    check('no sideways scroll on a phone', wide <= 360, wide)
    page.screenshot(path=str(S / 'dj-phone.png'), full_page=True)
    page.set_viewport_size({'width': 1280, 'height': 1000}); w(100)
    page.click('#dj-switch'); w(300)
    check('switch hides the panel', not page.locator('#dj-panel').is_visible())
    check('main deck name back', page.inner_text('#main-deck-legend').upper() == 'DECK')
    check('no page errors', not errs, errs[:5])
    b.close()
print(sum(R), 'of', len(R)); sys.exit(0 if all(R) else 1)
